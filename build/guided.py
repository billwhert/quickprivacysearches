"""Guided topics: load, validate, review status, review sheet, and the `approve` command.

A guided topic is a hand-built research path (topics/*.yaml). It cites provisions by chunk id; the
exact text is always pulled from the stored chunk, never retyped.

Lifecycle
  status: draft      excluded from the production site (shown only when INCLUDE_DRAFT_TOPICS=1)
  status: published  shown; every cited provision's text fingerprint (reviewed_hashes) must still
                     match, otherwise the topic is flagged "needs review" on the site and in the build

    python build/guided.py approve <topic-id> --by "Name"   # after you have reviewed the provisions
    python build/guided.py status                           # one line per topic
    python build/guided.py review                           # regenerate data/reports/guided_topics_review.md
"""
import argparse
import datetime
import hashlib
import os
import re
import sys

import yaml

from common import PROCESSED, REPORTS, ROOT, norm, read_json

TOPICS_DIR = ROOT / "topics"
DISCLAIMER = ("This page lists what the cited provisions say. It is a research aid, not legal advice, "
              "and it does not say what any organization must do to comply. Check the official source "
              "and the version date shown for each provision.")
STATUSES = ("draft", "published")


def fingerprint(chunk: dict) -> str:
    return hashlib.sha256(norm(chunk["text"]).encode("utf-8")).hexdigest()[:16]


def load_chunks() -> dict:
    by_id = {}
    for d in sorted(PROCESSED.iterdir()):
        f = d / "chunks.json"
        if f.exists():
            for c in read_json(f):
                by_id[c["chunk_id"]] = c
    return by_id


def load_documents() -> dict:
    docs = {}
    for d in sorted(PROCESSED.iterdir()):
        f = d / "document.json"
        if f.exists():
            docs[d.name] = read_json(f)
    return docs


def load_topics() -> list[dict]:
    topics = []
    for p in sorted(TOPICS_DIR.glob("*.yaml")):
        t = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
        t["_path"] = p
        topics.append(t)
    return topics


def cited_ids(t: dict) -> list[str]:
    """Every chunk id a topic cites, in display order, without duplicates."""
    out = []
    for block in (t.get("applicability") or []) + (t.get("items") or []) + (t.get("related") or []):
        for cid in block.get("chunk_ids") or []:
            if cid not in out:
                out.append(cid)
    return out


def validate(topics: list[dict], by_id: dict) -> list[str]:
    """Return a list of errors (empty when everything is consistent)."""
    errs, ids = [], set()
    for t in topics:
        name = t.get("id", t["_path"].name)
        for field in ("id", "title", "scope", "status", "triggers", "items"):
            if not t.get(field):
                errs.append(f"{name}: missing '{field}'")
        if t.get("id") in ids:
            errs.append(f"{name}: duplicate topic id")
        ids.add(t.get("id"))
        if t.get("status") not in STATUSES:
            errs.append(f"{name}: status must be one of {STATUSES}")
        for i, it in enumerate(t.get("items") or []):
            if not it.get("label") or not it.get("chunk_ids"):
                errs.append(f"{name}: item {i + 1} needs a label and chunk_ids")
        for cid in cited_ids(t):
            if cid not in by_id:
                errs.append(f"{name}: cites '{cid}', which is not in the loaded text")
        wording = yaml.safe_dump(t.get("items") or [], allow_unicode=True).lower()
        if re.search(r"\byou must\b|\bto be compliant\b|\bmust comply\b", wording):
            errs.append(f"{name}: item wording tells the reader what to do; describe what the law says instead")
    for t in topics:
        for r in t.get("related") or []:
            if r.get("topic") and r["topic"] not in ids:
                errs.append(f"{t.get('id')}: related topic '{r['topic']}' does not exist")
    return errs


def review_state(t: dict, by_id: dict) -> tuple[str, list[str]]:
    """('draft' | 'published' | 'needs-review', changed chunk ids)."""
    if t.get("status") != "published":
        return "draft", []
    recorded = t.get("reviewed_hashes") or {}
    changed = [c for c in cited_ids(t) if c in by_id and recorded.get(c) != fingerprint(by_id[c])]
    return ("needs-review" if changed else "published"), changed


def include_drafts() -> bool:
    return os.environ.get("INCLUDE_DRAFT_TOPICS") == "1"


def visible(t: dict) -> bool:
    return t.get("status") == "published" or include_drafts()


# ---------- review sheet ----------

def write_review_sheet(topics: list[dict], by_id: dict, docs: dict) -> str:
    L = ["# Guided topics: review sheet", "",
         "Generated by `build/guided.py`. For each topic, read every cited provision against the official",
         "source, then publish with `python build/guided.py approve <topic-id> --by \"Your name\"`.", "",
         "Things to check for each provision: is it the right one for this heading, is anything missing,",
         "and does the wording of the heading describe what the law says (not what a business must do)?", ""]
    for t in topics:
        state, _ = review_state(t, by_id)
        L += [f"## {t['title']}  (`{t['id']}`, {state})", "", f"Scope: {t['scope']}", "",
              f"Triggers: {', '.join(t.get('triggers', []))}", ""]

        def provision(cid: str):
            c = by_id[cid]
            d = docs.get(c["doc_id"], {})
            text = c["text"].replace("\n", "\n> ")
            return [f"- [ ] **{c['section_ref']}** (`{cid}`) - {c['heading'] or ''}",
                    f"  - {d.get('version_label', '')}; retrieved {str(d.get('retrieved_at', ''))[:10]};"
                    f" [official source]({c['source_url']})",
                    "", f"> {text}", ""]

        if t.get("applicability"):
            L += ["### Does the law apply at all?", ""]
            for q in t["applicability"]:
                L += [f"**{q['question']}**", ""]
                if q.get("note"):
                    L += [f"_Summary shown on the page:_ {q['note']}", ""]
                for cid in q.get("chunk_ids", []):
                    L += provision(cid)
        L += ["### What the provisions say", ""]
        for i, it in enumerate(t["items"], 1):
            L += [f"**{i}. {it['label']}**", ""]
            if it.get("summary"):
                L += [f"_Summary shown on the page:_ {it['summary']}", ""]
            for cid in it["chunk_ids"]:
                L += provision(cid)
        if t.get("related"):
            L += ["### Related", ""]
            for r in t["related"]:
                L += [f"- {r['label']}" + (f" -> topic `{r['topic']}`" if r.get("topic") else "")]
                for cid in r.get("chunk_ids", []):
                    L += ["  " + x for x in provision(cid)[:2]]
            L += [""]
    REPORTS.mkdir(parents=True, exist_ok=True)
    out = REPORTS / "guided_topics_review.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    return str(out)


# ---------- approve ----------

def approve(topic_id: str, by: str) -> None:
    by_id = load_chunks()
    topics = load_topics()
    errs = validate(topics, by_id)
    if errs:
        raise SystemExit("Fix these first:\n  " + "\n  ".join(errs))
    t = next((x for x in topics if x.get("id") == topic_id), None)
    if t is None:
        raise SystemExit(f"no topic '{topic_id}'")
    path = t["_path"]
    s = path.read_text(encoding="utf-8")
    s = re.sub(r"(?m)^status:.*$", "status: published", s)
    s = re.sub(r"(?m)^reviewed_by:.*$", f'reviewed_by: "{by}"', s)
    s = re.sub(r"(?m)^reviewed_at:.*$", f'reviewed_at: "{datetime.date.today().isoformat()}"', s)
    s = re.sub(r"(?ms)^reviewed_hashes:.*\Z", "", s).rstrip() + "\n"
    s += "\n# Fingerprint of each cited provision's text when it was reviewed (written by `approve`).\n"
    s += "reviewed_hashes:\n" + "".join(f'  "{c}": "{fingerprint(by_id[c])}"\n' for c in cited_ids(t))
    path.write_text(s, encoding="utf-8")
    print(f"{topic_id}: published, reviewed by {by} on {datetime.date.today()} "
          f"({len(cited_ids(t))} provisions fingerprinted)")


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("approve")
    a.add_argument("topic_id")
    a.add_argument("--by", required=True)
    sub.add_parser("status")
    sub.add_parser("review")
    args = ap.parse_args()
    if args.cmd == "approve":
        approve(args.topic_id, args.by)
        return
    by_id, topics = load_chunks(), load_topics()
    if args.cmd == "review":
        print(write_review_sheet(topics, by_id, load_documents()))
        return
    errs = validate(topics, by_id)
    for t in topics:
        state, changed = review_state(t, by_id)
        extra = f" ({len(changed)} provisions changed since review)" if changed else ""
        print(f"{t['id']}: {state}{extra}")
    for e in errs:
        print("ERROR", e)
    sys.exit(1 if errs else 0)


if __name__ == "__main__":
    main()
